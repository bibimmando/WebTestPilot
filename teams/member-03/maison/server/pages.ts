export function findInfoPage(slug: string): InfoPage | undefined {
  return infoPages.find((p) => p.slug === slug);
}

/** 목록 화면과 푸터가 쓴다. 본문(sections)은 빼고 보낸다.
 *  목록이 6개 페이지의 전체 본문을 받을 이유가 없다. */
export function listInfoPages() {
  return infoPages.map(({ slug, title, eyebrow, intro }) => ({
    slug,
    title,
    eyebrow,
    intro,
  }));
}
