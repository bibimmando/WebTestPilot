    const ready = () => page.waitForFunction(() => document.querySelector('[data-email-app]')?.getAttribute('aria-busy') === 'false');
    const click = async (id) => { await byId(id).click(); await ready(); };
    const back = async () => { if (name === 'mobile' && await byId('back-list').isVisible()) await click('back-list'); };
