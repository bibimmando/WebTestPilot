/** Isolated real backend used by browser tests. Never touches the developer DB. */
import { spawn, execFile } from 'node:child_process';
import { createServer } from 'node:net';
import { mkdir, rm } from 'node:fs/promises';
import { resolve } from 'node:path';
import { randomBytes } from 'node:crypto';

export const TEST_PASSWORD = 'A strong test password 2026!';

export async function startAuthServer({ origins = [], staticDir = process.env.AUTH_TEST_DIST } = {}) {
  const portServer = createServer();
  await new Promise((done) => portServer.listen(0, '127.0.0.1', done));
  const port = portServer.address().port;
  await new Promise((done) => portServer.close(done));
  await mkdir('backend/data', { recursive: true });
  const database = resolve(`backend/data/e2e-${randomBytes(12).toString('hex')}.db`);
  const devToken = randomBytes(32).toString('hex');
  const base = `http://127.0.0.1:${port}`;
  const python = process.env.AUTH_TEST_PYTHON || resolve(process.platform === 'win32' ? '.venv/Scripts/python.exe' : '.venv/bin/python');
  const server = spawn(python, ['-m', 'uvicorn', 'backend.tests.browser_app:app', '--host', '127.0.0.1', '--port', String(port), '--no-access-log'], {
    windowsHide: true,
    env: { ...process.env, ...(staticDir ? { AUTH_TEST_DIST: resolve(staticDir) } : {}), APP_ENV: 'test', DATABASE_URL: `sqlite:///${database.replace(/\\/g, '/')}`, AUTH_ORIGINS: [base, ...origins].join(','), AUTH_AUTO_MIGRATE: 'true', AUTH_COOKIE_SECURE: 'false', AUTH_DEV_ADMIN: 'true', AUTH_DEV_TOKEN: devToken, AUTH_SESSION_TTL: '300' },
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  let output = ''; let startupError;
  server.stdout.on('data', (data) => { output = (output + data).slice(-8000); });
  server.stderr.on('data', (data) => { output = (output + data).slice(-8000); });
  server.on('error', (error) => { startupError = error; });
  const stop = async () => {
    if (server.exitCode === null && !startupError) {
      const done = new Promise((resolve) => server.once('exit', resolve));
      if (process.platform === 'win32') {
        // Windows venv launchers can have an interpreter child; stop only this spawned tree.
        await new Promise((resolve) => execFile('taskkill', ['/PID', String(server.pid), '/T', '/F'], { windowsHide: true }, resolve));
      } else server.kill();
      await done;
    }
    // Only delete the single file generated by this function, never a shared DB or directory.
    await rm(database, { force: true }).catch((error) => { console.warn(`Test database cleanup: ${error.code}; retained ${database}`); });
  };
  try {
    for (let i = 0; i < 100; i++) {
      if (startupError) throw startupError;
      if (server.exitCode !== null) throw Error(`Test backend exited: ${output}`);
      try { if ((await fetch(`${base  }/api/health`)).ok) return { base, devToken, stop }; } catch { /* startup pending */ }
      await new Promise((resolve) => setTimeout(resolve, 100));
    }
    throw Error(`Test backend did not start: ${output}`);
  } catch (error) { await stop(); throw error; }
}

export async function createTestAccount(context, base, username, displayName = 'John Doe') {
  const token = (await (await context.request.get(`${base  }/api/auth/csrf`)).json()).csrfToken;
  const headers = { Origin: base, 'X-CSRF-Token': token };
  const result = await context.request.post(`${base  }/api/auth/register`, { headers, data: { username, displayName, password: TEST_PASSWORD, confirmPassword: TEST_PASSWORD } });
  if (result.status() !== 201) throw Error(`Test registration failed: ${await result.text()}`);
  const login = await context.request.post(`${base  }/api/auth/login`, { headers, data: { identifier: username, password: TEST_PASSWORD } });
  if (!login.ok()) throw Error(`Test login failed: ${await login.text()}`);
  return (await login.json()).user;
}
